ALTER TABLE tbl_user
    ADD COLUMN IF NOT EXISTS require_password_change BOOLEAN DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS tbl_user_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor CHARACTER VARYING(255) NOT NULL,
    action CHARACTER VARYING(255) NOT NULL,
    target_user_id BIGINT NOT NULL REFERENCES tbl_user(id),
    target_username CHARACTER VARYING(255) NOT NULL,
    change_summary CHARACTER VARYING(2000) NOT NULL,
    created_at TIMESTAMP DEFAULT NOW() NOT NULL
);
